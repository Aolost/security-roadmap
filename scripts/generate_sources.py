#!/usr/bin/env python3
"""Generate SOURCES.md from data/sources.yaml.

Deterministic and offline: entries are sorted by ID, and the output depends only on
the YAML input (no timestamps, no network), so repeated runs give identical bytes.

Usage:
  generate_sources.py              write SOURCES.md
  generate_sources.py --check      exit 1 if SOURCES.md differs from what would be generated
  generate_sources.py --stdout     print the generated Markdown
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCES = REPO_ROOT / "data" / "sources.yaml"
DEFAULT_OUTPUT = REPO_ROOT / "SOURCES.md"
UNKNOWN = "unknown"

# Characters that can change Markdown meaning inside running text or table cells.
_MD_SPECIAL = re.compile(r"([\\`*_\[\]<>|#~&!])")


_URL_IN_TEXT = re.compile(r"https?://[^\s<>]*[^\s<>.,;:!?)\]'\"]")


def md(text: object) -> str:
    """Escape a value for safe use in Markdown text or a table cell.

    URLs inside free text become autolinks (<https://...>) instead of being escaped.
    """
    flat = " ".join(str(text).split())
    out, pos = [], 0
    for match in _URL_IN_TEXT.finditer(flat):
        out.append(_MD_SPECIAL.sub(r"\\\1", flat[pos:match.start()]))
        out.append(f"<{match.group(0)}>")
        pos = match.end()
    out.append(_MD_SPECIAL.sub(r"\\\1", flat[pos:]))
    return "".join(out)


def md_url(url: str) -> str:
    """Render a URL as an autolink; reject characters that would break it."""
    if url == UNKNOWN:
        return "unknown"
    if any(ch in url for ch in "<> \t\n"):
        raise ValueError(f"URL cannot be rendered safely: {url!r}")
    return f"<{url}>"


def _as_str(value: object) -> str:
    if isinstance(value, (dt.date, dt.datetime)):
        return value.isoformat()
    return str(value)


def describe_retrieval(src: dict) -> str:
    status = src.get("http_status", UNKNOWN)
    final_status = src.get("final_http_status", status)
    url, final_url = src["url"], src.get("final_url", UNKNOWN)
    if status == UNKNOWN:
        return f"HTTP status unknown; observed destination {md_url(final_url)}"
    if isinstance(status, int) and 300 <= status < 400:
        return (
            f"requested URL answered HTTP {status} (redirect); final destination "
            f"{md_url(final_url)} answered HTTP {final_status}"
        )
    if final_url == url:
        return f"HTTP {status}, no redirect"
    return f"HTTP {status}; observed destination {md_url(final_url)}"


def render_entry(src: dict) -> list[str]:
    sid = src["id"]
    lines = [f"### {sid}", ""]
    prereqs = src.get("prerequisites") or []
    hours = src.get("est_hours", UNKNOWN)
    fields: list[tuple[str, str]] = [
        ("Title", md(src["title"])),
        ("URL", md_url(src["url"])),
        ("Retrieval", describe_retrieval(src)),
        ("Page title as observed", md(src["page_title"])),
        ("Type", md(src["type"])),
        ("Cost", md(src["cost"])),
    ]
    if src.get("cost_notes"):
        fields.append(("Cost notes", md(src["cost_notes"])))
    fields += [
        ("Difficulty", md(src["difficulty"])),
        ("Estimated hours (editorial)", md(hours)),
        ("Prerequisites (editorial)", "; ".join(md(p) for p in prereqs) if prereqs else "none"),
        ("Why included", md(src["why_included"])),
    ]
    book = src.get("book")
    if book:
        authors = book["authors"]
        author_text = ", ".join(md(a) for a in authors) if isinstance(authors, list) else md(authors)
        fields += [
            ("Book authors", author_text),
            ("Book edition", md(book["edition"])),
            ("Book details confirmed at", md_url(book["details_source"])),
        ]
    cert = src.get("certification")
    if cert:
        fields += [
            ("Certification prerequisites", md(cert["prerequisites"])),
            ("Certification price", md(cert["price"])),
            ("Exam format", md(cert["exam_format"])),
            ("Certification details checked on", md(_as_str(cert["checked_on"]))),
        ]
    if src.get("notes"):
        fields.append(("Notes", md(src["notes"])))
    verified = md(_as_str(src["verified_on"]))
    if src.get("verified_with"):
        verified += f" (with {md(src['verified_with'])})"
    fields.append(("Verified on", verified))

    lines += [f"- **{label}:** {value}" for label, value in fields]
    lines.append("")
    return lines


def render(data: dict) -> str:
    sources = sorted(data["sources"], key=lambda s: s["id"])
    out = [
        "# Sources",
        "",
        "<!-- Generated by scripts/generate_sources.py from data/sources.yaml. Do not edit by hand. -->",
        "",
        "This file is generated from [`data/sources.yaml`](data/sources.yaml). To change it, edit the YAML",
        "and run `make sources`. Retrieval details record what was observed when each URL was opened on",
        "the date shown. Estimated hours and prerequisites are editorial opinions.",
        "",
        f"Total resources: {len(sources)}",
        "",
        "## Summary",
        "",
        "| ID | Title | Type | Cost | Difficulty | Final status | Verified on |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for src in sources:
        final_status = src.get("final_http_status", src.get("http_status", UNKNOWN))
        redirected = isinstance(src.get("http_status"), int) and 300 <= src["http_status"] < 400
        status_text = f"{final_status} (after redirect)" if redirected else str(final_status)
        out.append(
            f"| [{src['id']}](#{src['id']}) | {md(src['title'])} | {md(src['type'])} | {md(src['cost'])} "
            f"| {md(src['difficulty'])} | {md(status_text)} | {md(_as_str(src['verified_on']))} |"
        )
    out += ["", "## Entries", ""]
    for src in sources:
        out += render_entry(src)
    return "\n".join(out).rstrip("\n") + "\n"


def generate(sources_path: Path = DEFAULT_SOURCES) -> str:
    with sources_path.open(encoding="utf-8") as handle:
        return render(yaml.safe_load(handle))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate SOURCES.md from data/sources.yaml.")
    parser.add_argument("--sources", type=Path, default=DEFAULT_SOURCES)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if the output file is out of date")
    mode.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = parser.parse_args(argv)

    text = generate(args.sources)
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        current = args.output.read_bytes() if args.output.exists() else b""
        if current != text.encode("utf-8"):
            print(f"{args.output} is out of date; run `make sources` and commit the result.", file=sys.stderr)
            return 1
        print(f"{args.output} matches {args.sources}")
        return 0
    args.output.write_bytes(text.encode("utf-8"))
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
